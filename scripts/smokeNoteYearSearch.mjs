/**
 * 사진첩 제목 검색 — **연도 토큰** 규칙 스모크.
 *
 * ★ 문제: 연도를 치면 그 해 기출이 나와야 하는데, 부분일치라 "2026"이
 *   `KakaoTalk_20260731_100015171_08.jpg` 같은 **날짜 문자열 안**에 걸렸다(실측 157건).
 *   전공스샷의 실제 2026 기출 24건이 그 사이에 묻힌다.
 * ⇒ 4자리 연도(19xx·20xx)는 **앞뒤에 숫자가 붙지 않은 경우**만 맞춘다.
 *   연도가 아닌 검색어는 기존 부분일치를 그대로 쓴다(회귀 방지).
 */
import { matchesNoteSearch, noteSearchTokens, notePhotoTitle } from "../types/notes.ts";

let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass += 1; } else { fail += 1; console.log("  ✗", m); } };

const p = (fileName, title) => ({ fileName, title });
const hit = (photo, q) => matchesNoteSearch(photo, noteSearchTokens(q));

// ── 1. 연도 검색은 그 해 기출만 ──────────────────────────────
const y2026 = [p("2026 A-2.png"), p("2026 전기 B-11.png"), p("2026-3.png")];
for (const ph of y2026) ok(hit(ph, "2026"), `2026 기출이 안 잡힘: ${ph.fileName}`);

// ★ 날짜 문자열 안의 연도는 걸리면 안 된다
const noise = [
  p("KakaoTalk_20260731_100015171_08.jpg"),
  p("IMG_20260415_123456.png"),
  p("scan-20261231.png"),
  p("20260101_회로.png"),
];
for (const ph of noise) ok(!hit(ph, "2026"), `날짜 문자열이 연도로 잡힘: ${ph.fileName}`);

// 다른 해는 안 잡힌다
ok(!hit(p("2025 A-2.png"), "2026"), "다른 연도가 잡힘");
ok(!hit(p("12026.png"), "2026"), "앞에 숫자가 붙은 값이 잡힘");
ok(!hit(p("20260.png"), "2026"), "뒤에 숫자가 붙은 값이 잡힘");

// 경계: 연도가 제목 맨 앞/뒤/가운데 어디에 있어도 잡힌다
ok(hit(p("2013 A-21.png"), "2013"), "맨 앞 연도");
ok(hit(p("기출 2013.png"), "2013"), "맨 뒤 연도");
ok(hit(p("임용 2013 전자 A-4.png"), "2013"), "가운데 연도");
// 구분 기호가 붙어도(하이픈·언더바·괄호) 숫자만 아니면 잡힌다
ok(hit(p("2007-15.png"), "2007"), "하이픈 뒤 번호");
ok(hit(p("(2011)_A-20.png"), "2011"), "괄호로 감싼 연도");

// ── 2. 연도 + 다른 토큰 (AND) ────────────────────────────────
ok(hit(p("2021 전기 A-12.png"), "2021 전기"), "연도+트랙 AND 실패");
ok(!hit(p("2021 A-12.png"), "2021 전기"), "전자 기출이 '전기'로 잡힘");
ok(hit(p("2021 전기 A-12.png"), "전기 2021"), "토큰 순서 무관 실패");

// ── 3. 연도가 아닌 검색어는 기존 부분일치 유지(회귀) ─────────
ok(hit(p("테브난 등가.png"), "테브난"), "한글 부분일치 회귀");
ok(hit(p("테브난 등가.png"), "테브난등가"), "띄어쓰기 무시 회귀");
ok(hit(p("2011 A-20.png"), "A-20"), "번호 부분일치 회귀");
ok(hit(p("KakaoTalk_20260731_1.jpg"), "kakao"), "파일명 부분일치 회귀");
// 4자리라도 연도 범위 밖이면 부분일치 그대로
ok(hit(p("no_1234_5678.png"), "1234"), "연도 아닌 4자리는 부분일치여야 함");
ok(hit(p("x20260731.png"), "2607"), "연도 아닌 토큰은 부분일치여야 함");

// ── 4. 제목을 직접 적었으면 그쪽이 대상 ──────────────────────
ok(hit(p("IMG_0001.png", "2019 전자 A-6 테브난"), "2019"), "직접 적은 제목의 연도 실패");
ok(!hit(p("2019 A-6.png", "테브난 등가"), "2019"), "제목이 있으면 파일명은 안 본다");
ok(notePhotoTitle(p("2019 A-6.png")) === "2019 A-6", "제목 = 확장자 뗀 파일명");

// ── 5. 빈 검색어는 전부 통과 ─────────────────────────────────
ok(hit(p("아무거나.png"), ""), "빈 검색어가 막힘");
ok(hit(p("아무거나.png"), "   "), "공백 검색어가 막힘");

console.log(`\n=== NOTE 연도 검색: ${pass} pass / ${fail} fail ===`);
if (fail > 0) process.exit(1);
